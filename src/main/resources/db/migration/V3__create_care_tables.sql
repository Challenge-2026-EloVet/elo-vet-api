-- ===============================================================================
-- ELO VET - TABELAS DO FLUXO DE PLANO DE CUIDADO
-- Até aqui essas tabelas eram criadas pelo Hibernate (ddl-auto=update).
-- IF NOT EXISTS mantém intactas as tabelas que já existem nos bancos atuais
-- e as cria com a mesma estrutura em bancos novos.
-- ===============================================================================

CREATE TABLE IF NOT EXISTS care_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    veterinary_id BIGINT,
    pet_id BIGINT,
    pet_owner_id BIGINT,
    created_at TIMESTAMP(6),
    created_by_user_id BIGINT,
    status VARCHAR(255),
    notes VARCHAR(255),
    CONSTRAINT pk_care_plan PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS care_plan_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    care_plan_id BIGINT,
    title VARCHAR(255),
    description VARCHAR(255),
    due_date DATE,
    status VARCHAR(255),
    CONSTRAINT pk_care_plan_item PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    target_user_id BIGINT,
    care_plan_id BIGINT,
    type VARCHAR(255),
    payload VARCHAR(255),
    sent_at TIMESTAMP(6),
    CONSTRAINT pk_notification PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS follow_up_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    care_plan_item_id BIGINT,
    action VARCHAR(255),
    performed_by BIGINT,
    performed_at TIMESTAMP(6),
    note VARCHAR(255),
    CONSTRAINT pk_follow_up_log PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_care_plan_pet_owner ON care_plan (pet_owner_id);
CREATE INDEX IF NOT EXISTS ix_care_plan_item_care_plan ON care_plan_item (care_plan_id);
CREATE INDEX IF NOT EXISTS ix_care_plan_item_status_due_date ON care_plan_item (status, due_date);
